def validate(root, project=None, workspace=None, deep=False):
    out = {'pass': True,
           'scope': 'Local checkpoint integrity (whole chain) and optional local artifact hashes only; '
                    'not remote freshness, semantic approval or complete secret detection',
           'projects': []}
    paths = [project_dir(root, project)] if project else all_projects(root)
    if not paths:
        raise HandoffError('No project checkpoints found')
    for p in paths:
        h, cp = checked_head(p)
        seen, _, advisories = walk_chain(p, cp, deep=deep)
        warnings, verified = [], []
        if not (p / 'CURRENT.md').exists() or (p / 'CURRENT.md').read_bytes() != current_bytes(cp):
            warnings.append('CURRENT.md missing/stale; run rebuild')
        orphans = [z.stem for z in (p / 'checkpoints').glob('*.json') if z.stem not in seen]
        if orphans:
            warnings.append('Unreferenced checkpoints require review: ' + ','.join(sorted(orphans)))
        if (p / '.write.lock').exists():
            warnings.append('Project lock exists; inspect active writer before editing')
        if workspace:
            for a in cp['state']['artifacts']:
                if a['availability'] == 'REMOTE_ONLY':
                    continue
                f = inside(workspace, a['local_path'])
                if not f.is_file() or digest(f.read_bytes()) != a['sha256']:
                    raise HandoffError('Missing/changed local artifact: ' + a['id'] + ' in ' + project_id(p))
                verified.append(a['id'])
        entry = {'project': project_id(p), 'head': h, 'checkpoints_checked': len(seen),
                 'local_artifacts_verified': verified, 'warnings': warnings, 'lint': lint_state(cp['state'])}
        if deep:
            entry['ancestor_advisories'] = advisories
        out['projects'].append(entry)
    out['unloaded_projects'] = sorted(set(retained_index_rows(root)) - {project_id(p) for p in all_projects(root)})
    out['index_current'] = (Path(root) / 'INDEX.md').exists() and (Path(root) / 'INDEX.md').read_bytes() == index_bytes(root)
    return out


def resume_text(root, project):
    p = project_dir(root, project)
    h, cp = checked_head(p)
    seen, missing, _ = walk_chain(p, cp, allow_missing=True)
    s = cp['state']
    hd = s['handoff']
    lines = [f"# 接手简报：{s['title']}", '',
             f"项目 `{project}` · 状态 **{s['status']}** · 检查点 `{h['checkpoint_id']}` · rev {h['revision']} · 更新 {cp['updated_at']}",
             f"最近变化：{_inline(cp['note'])}"]
    integrity = f'完整性：HEAD 指纹通过；父链已校验 {len(seen)} 个检查点'
    if missing:
        integrity += f'；本地缺 {len(missing)} 个祖先（未校验，属本地恢复不完整，不代表远端丢失）'
    lines.append(integrity)
    if (p / '.write.lock').exists():
        lines.append('⚠ 存在写锁 .write.lock：先核实是否有进行中的写入，工具不会自动抢锁')
    if not (p / 'CURRENT.md').exists() or (p / 'CURRENT.md').read_bytes() != current_bytes(cp):
        lines.append('⚠ CURRENT.md 过时：运行 rebuild（派生视图，不影响 HEAD）')
    lines += ['', '## 接手第一步', _inline(hd.get('first_action', ''))]
    for k in RESUME_HANDOFF_KEYS:
        if hd.get(k):
            lines.append(f'- {k}: {_inline(hd[k])}')
    lines += ['', '## 目标', _inline(s['goal'])]

    def block(title, key, items, limit=None, newest=False):
        chosen = items[-limit:] if (limit and newest) else (items[:limit] if limit else items)
        more = len(items) - len(chosen)
        out = ['', f'## {title}（{len(items)}）'] + ['- ' + render_item(key, x) for x in chosen]
        if more > 0:
            out.append(f'- …另有 {more} 项，见 CURRENT.md / read')
        return out if items else ['', f'## {title}', '无。']

    lines += block('未完成', 'pending', s['pending'])
    lines += block('下一步', 'next_actions', s['next_actions'])
    lines += block('运行中的任务（先确认是否仍在运行）', 'running_operations', hd.get('running_operations', []))
    lines += block('当前约束', 'constraints', s['constraints'])
    lines += block('不要重复的错误', 'avoid', s['avoid'])
    lines += block('最近决定', 'decisions', s['decisions'], limit=8, newest=True)
    lines += block('最近完成', 'completed', s['completed'], limit=5, newest=True)
    lines += block('风险', 'risks', s['risks'], limit=5)
    lines += ['', f"产物 {len(s['artifacts'])} 项、证据 {len(s['evidence'])} 项：见 CURRENT.md；"
                  '本地素材核验用 validate --verify-local。']
    lint = lint_state(s)
    if lint:
        lines += ['', '## 提示（不阻断）'] + ['- ' + x for x in lint]
    scripts = Path(__file__).resolve().parent
    root_arg = '' if Path(root).resolve() == DEFAULT_ROOT.resolve() else f' --root {root}'
    lines += ['', '## 写入本项目', '先把补丁写到 /tmp/patch.json（规范见 references/state-schema.md），然后：',
              f"python3 {scripts / 'handoff.py'}{root_arg} update --project {project} "
              f"--expected {h['checkpoint_id']} --patch /tmp/patch.json --note '本次实际变化及证据' [--dry-run]",
              f"python3 {scripts / 'progress_sync.py'}{root_arg} --token-file /tmp/.gh_token push "
              f"--project {project} -m '{project}: 变化摘要'"]
    return '\n'.join(lines) + '\n'


# ---------------------------------------------------------------- CLI

def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--root', type=Path, default=DEFAULT_ROOT)
    sub = ap.add_subparsers(dest='command', required=True)
    sub.add_parser('list')
    sub.add_parser('rebuild')
    for name in ('read', 'resume', 'state'):
        c = sub.add_parser(name)
        c.add_argument('--project', required=True)
    sub.choices['read'].add_argument('--allow-missing-parents', action='store_true',
                                     help='report locally missing ancestors instead of failing (reading only)')
    c = sub.add_parser('checkpoint')
    c.add_argument('--project', required=True)
    c.add_argument('--expected', required=True)
    c.add_argument('--state', required=True, help='state JSON file, or - for stdin')
    c.add_argument('--note', required=True)
    c.add_argument('--merge-parent')
    u = sub.add_parser('update')
    u.add_argument('--project', required=True)
    u.add_argument('--expected', required=True)
    u.add_argument('--patch', required=True, help='patch JSON file, or - for stdin')
    u.add_argument('--note', required=True)
    u.add_argument('--dry-run', action='store_true')
    v = sub.add_parser('validate')
    v.add_argument('--project')
    v.add_argument('--deep', action='store_true', help='also re-check ancestor content (advisory)')
    v.add_argument('--verify-local', action='store_true')
    v.add_argument('--workspace', type=Path, default=Path('/home/user'))
    a = ap.parse_args(argv)
    try:
        if a.command == 'resume':
            sys.stdout.write(resume_text(a.root, a.project))
            return 0
        if a.command == 'read':
            p = project_dir(a.root, a.project)
            _, result = checked_head(p)
            _, missing, _ = walk_chain(p, result, allow_missing=a.allow_missing_parents)
            if missing:
                print(f'warning: {len(missing)} ancestor checkpoint(s) missing locally; chain only partly verified',
                      file=sys.stderr)
        elif a.command == 'state':
            p = project_dir(a.root, a.project)
            _, cp = checked_head(p)
            chain(p, cp)
            result = cp['state']
        elif a.command == 'checkpoint':
            state = load_input(a.state)
            h = checkpoint(a.root, a.project, state, a.expected, a.note, a.merge_parent)
            result = dict(h, lint=lint_state(state))
        elif a.command == 'update':
            result = update(a.root, a.project, load_input(a.patch), a.expected, a.note, a.dry_run)
        elif a.command == 'rebuild':
            rebuild(a.root)
            result = {'rebuilt': True}
        elif a.command == 'validate':
            result = validate(a.root, a.project, a.workspace if a.verify_local else None, a.deep)
        else:
            result = []
            for p in all_projects(a.root):
                h, cp = checked_head(p)
                result.append({'project': project_id(p), 'title': cp['state']['title'], 'status': cp['state']['status'],
                               'head': h['checkpoint_id'], 'revision': h['revision'], 'updated_at': cp['updated_at']})
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0
    except (HandoffError, OSError, ValueError, KeyError, TypeError) as e:
        # Never echo input state or caught raw data, which may contain secrets.
        print('Handoff failed: ' + (str(e) if isinstance(e, HandoffError) else type(e).__name__), file=sys.stderr)
        return 1
    except Exception as e:  # noqa: BLE001 - last-resort guard without leaking data
        print('Handoff failed unexpectedly: ' + type(e).__name__, file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
