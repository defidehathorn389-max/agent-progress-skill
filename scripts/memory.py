def validate(root):
    root = Path(root)
    counts = {kind: len(load_items(root, kind)) for kind in KINDS}
    for f in (root / 'changes').glob('*.json') if (root / 'changes').exists() else []:
        entry = json.loads(f.read_text(encoding='utf-8'))
        if not ID_RE.fullmatch(entry.get('id', '')) or f.stem != entry['id']:
            raise MemError(f'invalid change entry {f.name}')
    load_focus(root)
    before = {name: (root / name).read_bytes() if (root / name).exists() else None for name in DERIVED}
    render(root)
    current = all(before[name] == (root / name).read_bytes() for name in DERIVED)
    for name, data in before.items():  # validate must not modify the tree
        if data is None:
            (root / name).unlink()
        else:
            handoff.atomic(root / name, data)
    expired = [x['id'] for _, x in expired_items(root)]
    dupes = []
    for kind in ('preference', 'fact', 'lesson'):
        live = active(root, kind)
        for i, x in enumerate(live):
            for y in live[i + 1:]:
                sc = similarity(_head(x), _head(y))
                if sc >= DUPLICATE_REPORT:
                    dupes.append({'a': x['id'], 'b': y['id'], 'similarity': round(sc, 2)})
    cats = load_categories(root)
    known = {c['id'] for c in cats}
    live = [x for k in ('preference', 'fact', 'lesson') for x in active(root, k, LIVE)]
    unknown = [x['id'] for x in live if x.get('category') and x['category'] not in known]
    if unknown:
        raise MemError(f'unknown category on {unknown[:5]} (add it to {CATEGORIES_FILE} or fix the item)')
    result = {'pass': True, 'counts': counts, 'views_current': current, 'expired_pending': expired,
              'possible_duplicates': dupes[:20]}
    if cats:
        result['uncategorized'] = [x['id'] for x in live if not x.get('category')]
    result['needs_review'] = [x['id'] for x in live if REVIEW_TAG in x.get('tags', [])]
    return result


